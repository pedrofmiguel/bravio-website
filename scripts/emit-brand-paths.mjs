/** Emits the traced logo geometry as a TS module so the marks can be inlined
 *  and animated without a network round-trip.
 *
 *  The viewBox is tightened to the artwork's real bounding box (measured by
 *  scripts/measure-bbox.mjs) rather than the source PNG's canvas. Without that
 *  the logomark only fills ~64% of its box and every size class in the app has
 *  to compensate by guesswork.
 *
 *  Pipeline: trace-logo.mjs -> measure-bbox.mjs -> emit-brand-paths.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const bbox = JSON.parse(readFileSync("scripts/bbox.json", "utf8"));
const lockup = JSON.parse(readFileSync("scripts/lockup.json", "utf8"));

function extract(file, key) {
  const svg = readFileSync(`public/brand/${file}`, "utf8");
  const d = svg.match(/<path[^>]*\sd="([^"]+)"/)[1];
  const { x, y, width, height } = bbox[key];
  // A whisker of breathing room so antialiased edges are never clipped.
  const pad = Math.max(width, height) * 0.01;
  const viewBox = [
    (x - pad).toFixed(2),
    (y - pad).toFixed(2),
    (width + pad * 2).toFixed(2),
    (height + pad * 2).toFixed(2),
  ].join(" ");
  return { viewBox, d };
}

const mark = extract("logomark.svg", "logomark");
const word = extract("wordmark.svg", "wordmark");

writeFileSync(
  "src/lib/brand-paths.ts",
  `// GENERATED by scripts/emit-brand-paths.mjs - do not edit by hand.
// Source: public/brand/*.png traced via scripts/trace-logo.mjs
// viewBox is cropped to the artwork's real bounds, so a width of 1em renders
// 1em of mark rather than 1em of mostly empty canvas.

export const LOGOMARK_VIEWBOX = "${mark.viewBox}";
export const LOGOMARK_PATH =
  "${mark.d}";

export const WORDMARK_VIEWBOX = "${word.viewBox}";
export const WORDMARK_PATH =
  "${word.d}";

/* Measured off the supplied lockup, both against the mark's height, which is
   the one size a caller picks. Keeps the header and footer from re-deciding
   the relationship between the two marks by eye. */
export const LOCKUP_WORD_RATIO = ${lockup.wordRatio.toFixed(4)};
export const LOCKUP_GAP_RATIO = ${lockup.gapRatio.toFixed(4)};
`
);
console.log("logomark viewBox:", mark.viewBox);
console.log("wordmark viewBox:", word.viewBox);
console.log("lockup ratios:", lockup.wordRatio.toFixed(4), lockup.gapRatio.toFixed(4));
